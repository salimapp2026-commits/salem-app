// Default locale. English while we match the Figma; see the note above.
const DEFAULT_LOCALE: Locale = 'en';

// While pinned, every setLocale() call resolves to DEFAULT_LOCALE. A stored
// profile preference of 'ar' would otherwise flip the UI back to Arabic/RTL
// mid-session and undo the English design. Flip this to false to re-enable the
// Arabic toggle.
export const LOCALE_PINNED = true;

let activeLocale: Locale = DEFAULT_LOCALE;

// Device detection is deliberately not consulted yet: the app is pinned to the
// English design. Kept for when the Arabic toggle is turned back on.
export function detectLocale(): Locale {
  const locales = getLocales();
  const tag = locales[0]?.languageCode ?? 'en';
  return tag.startsWith('ar') ? 'ar' : 'en';
}

export function setLocale(loc: Locale) {
  const next = LOCALE_PINNED ? DEFAULT_LOCALE : loc;
  activeLocale = next;
  const wantRtl = next === 'ar';
  if (I18nManager.isRTL !== wantRtl) {
    I18nManager.allowRTL(wantRtl);
    I18nManager.forceRTL(wantRtl);
    // Note: forceRTL only takes effect after a JS reload. We intentionally do
    // not auto-reload here — the caller can decide (e.g., on first launch).
  }
}

export function getLocale(): Locale {
  return activeLocale;
}

export function t(key: string): string {
  return messages[activeLocale][key] ?? messages.en[key] ?? key;
}

/** t() with {placeholders}: tf('trends.learning', { name: 'Amina', x: 6 }). */
export function tf(key: string, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_m, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}

// Date / time / number formatting must follow the active locale, not a
// hardcoded one. Passing 'ar' while the UI ships in English renders
// Arabic-Indic numerals (١٢:٣٠) inside English screens.
function intlTag(): string {
  return activeLocale === 'ar' ? 'ar-EG' : 'en-GB';
}

export function formatDate(value: string | number | Date): string {
  return new Date(value).toLocaleDateString(intlTag(), {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

export function formatTime(value: string | number | Date): string {
  return new Date(value).toLocaleTimeString(intlTag(), {
    hour: '2-digit',
    minute: '2-digit',
  });
}

export function formatDateTime(value: string | number | Date): string {
  return `${formatDate(value)} · ${formatTime(value)}`;
}

export function formatNumber(value: number): string {
  return value.toLocaleString(intlTag());
}

/**
 * Wrap user-supplied text (names, mostly) that is interpolated into a
 * sentence of the opposite direction. Without this, an Arabic name inside an
 * English line makes the bidi algorithm reorder the surrounding text —
 * "Dr. <arabic> · 20 Jun 2026" renders as "Dr. 20 <arabic> Jun 2026".
 * U+2068 FIRST STRONG ISOLATE / U+2069 POP DIRECTIONAL ISOLATE fence it off.
 */
export function isolate(value: string | null | undefined): string {
  if (!value) return '';
  return `\u2068${value}\u2069`;
}

