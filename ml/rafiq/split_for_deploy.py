"""Split model.json into small parts for the edge-function deploy.

    cd ml && python3 -m rafiq.split_for_deploy

Writes supabase/functions/_shared/rafiq/model/meta.json (everything but the
trees) + trees-NN.json (a few trees each, ~15 KB) + ../modelParts.ts, which
imports them and rebuilds the exact model. model.json stays the source of
truth (Python + tests); tests/rafiqModelParts.test.ts proves the parts rebuild
it exactly, and the deployed scorer re-checks the fingerprint at start.
"""
from __future__ import annotations

import json
import os

from .train import MODEL_PATH

MAX_BYTES = 15_000


def split():
    with open(MODEL_PATH) as fh:
        m = json.load(fh)
    out_dir = os.path.join(os.path.dirname(MODEL_PATH), 'model')
    os.makedirs(out_dir, exist_ok=True)
    for f in os.listdir(out_dir):
        if f.endswith('.json'):
            os.remove(os.path.join(out_dir, f))
    trees = m['forest']['trees']
    meta = {**m, 'forest': {k: v for k, v in m['forest'].items() if k != 'trees'}}
    with open(os.path.join(out_dir, 'meta.json'), 'w') as fh:
        json.dump(meta, fh, separators=(',', ':'))
    parts, cur = [], []
    for t in trees:
        if cur and len(json.dumps(cur + [t], separators=(',', ':'))) > MAX_BYTES:
            parts.append(cur); cur = []
        cur.append(t)
    if cur:
        parts.append(cur)
    for i, p in enumerate(parts):
        with open(os.path.join(out_dir, f'trees-{i:02d}.json'), 'w') as fh:
            json.dump(p, fh, separators=(',', ':'))
    names = [f'trees-{i:02d}' for i in range(len(parts))]
    ts = ['// GENERATED by ml/rafiq/split_for_deploy.py — do not edit. The trained model,',
          '// rebuilt from small JSON parts (small files deploy reliably). Source of truth:',
          '// model.json; tests/rafiqModelParts.test.ts proves this rebuilds it exactly.',
          "import type { RafiqModel } from './model.ts';",
          "import meta from './model/meta.json' with { type: 'json' };"]
    ts += [f"import t{i:02d} from './model/{n}.json' with {{ type: 'json' }};" for i, n in enumerate(names)]
    ts += ['',
           'const trees = [' + ', '.join(f'...t{i:02d}' for i in range(len(parts))) + '];',
           '// deno-lint-ignore no-explicit-any',
           'const m = meta as any;',
           'export const model = { ...m, forest: { ...m.forest, trees } } as unknown as RafiqModel;',
           '']
    with open(os.path.join(os.path.dirname(MODEL_PATH), 'modelParts.ts'), 'w') as fh:
        fh.write('\n'.join(ts))
    return len(parts)


if __name__ == '__main__':
    n = split()
    print(f'meta.json + {n} tree parts written')
